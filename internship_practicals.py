import time

def rule_based_chatbot():
    # Define a simple dictionary of rules (lowercase keys for easier matching)
    responses = {
        "hello": "Hello! Welcome to CODTECH IT Solutions. How can I assist you today?",
        "hi": "Hi there! What can I do for you?",
        "who are you": "I am a Rule-Based AI Chatbot developed by Shruti Deshmukh.",
        "internship": "The Artificial Intelligence internship duration is typically 1 to 4 months.",
        "bye": "Goodbye! Have a great day ahead!",
    }

    print("=== Project 2: Rule-Based Chatbot ===")
    print("Type 'bye' to exit the chat.\n")

    while True:
        user_input = input("You: ").strip().lower()

        if user_input == 'bye':
            print(f"Bot: {responses['bye']}")
            break

        # Find match using simple dictionary lookup
        matched_response = responses.get(user_input, "I am sorry, I am programmed with limited rules and didn't quite understand that. Could you ask something else?")

        time.sleep(0.4) # Simulating slight processing latency
        print(f"Bot: {matched_response}\n")

if __name__ == "__main__":
    rule_based_chatbot()

