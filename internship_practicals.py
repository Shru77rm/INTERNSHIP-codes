import torch
from transformers import GPT2LMHeadModel, GPT2Tokenizer

def generate_ai_text(prompt_text, max_output_length=60):
    print("=== Project 5: Generative Text Model (GPT-2) ===")

    # 1. Load Pre-trained GPT-2 Model and Tokenizer
    print("Loading pre-trained GPT-2 model weights from Hugging Face...")
    tokenizer = GPT2Tokenizer.from_pretrained("gpt2")
    model = GPT2LMHeadModel.from_pretrained("gpt2")

    # Set the model to evaluation mode (turns off dropout layers)
    model.eval()

    # 2. Tokenize Input Text (Convert string words into numeric Tensor IDs)
    input_ids = tokenizer.encode(prompt_text, return_tensors="pt")

    # 3. Generate Text Sequences using Advanced Decoding Parameters
    print("Generating response text...")
    with torch.no_grad(): # Disable gradient calculation for faster CPU/GPU inference
        output_sequences = model.generate(
            input_ids=input_ids,
            max_length=max_output_length,
            num_return_sequences=1,
            no_repeat_ngram_size=2,   # Prevents the model from repeating phrases
            do_sample=True,           # Enables probabilistic sampling for creative text
            top_k=50,                 # Keeps only the top 50 highest probability tokens
            top_p=0.92,               # Nucleus sampling: cumulative probability threshold
            temperature=0.85,         # Controls randomness (higher = more creative/random)
            pad_token_id=tokenizer.eos_token_id
        )

    # 4. Decode Token IDs back into human-readable text strings
    generated_text = tokenizer.decode(output_sequences[0], clean_up_tokenization_spaces=True)
    return generated_text

